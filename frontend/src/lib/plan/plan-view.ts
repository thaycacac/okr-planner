import type {
  AllocationOut,
  KeyResultOut,
  ObjectiveOut,
  QuarterDetail,
  QuarterSchedule,
  ScheduleDay,
  ScheduledTaskOut,
  TaskOut,
} from "@/lib/api/types";

export type TaskView = {
  task: TaskOut;
  code: string;
  objectiveIndex: number;
  krCode: string;
  scheduled: ScheduledTaskOut | null;
  late: boolean;
  /** Days the task occupies: its pins when pinned (they win over a stale schedule), else the schedule. */
  days: AllocationOut[];
  start: string | null;
  end: string | null;
  dependsOn: number[];
  blocks: number[];
  done: boolean;
  pinned: boolean;
  /** Added by the user rather than generated by a plan run. */
  isNew: boolean;
  /** Neither scheduled, pinned, late nor done: created or changed since the last schedule. */
  unplaced: boolean;
};

export type KrView = {
  kr: KeyResultOut;
  code: string;
  tasks: TaskView[];
  minutes: number;
  start: string | null;
  end: string | null;
};

export type ObjectiveView = {
  objective: ObjectiveOut;
  index: number;
  code: string;
  krs: KrView[];
  minutes: number;
  start: string | null;
  end: string | null;
};

/** Left out of planning by an applied option; the user can bring it back. */
export type DroppedItem =
  | { kind: "objective"; objective: ObjectiveOut; code: string; krCount: number; taskCount: number }
  | { kind: "kr"; kr: KeyResultOut; objective: ObjectiveOut; code: string; taskCount: number };

export type PlanView = {
  objectives: ObjectiveView[];
  dropped: DroppedItem[];
  tasks: Map<number, TaskView>;
  taskCount: number;
  krCount: number;
  totalMinutes: number;
  /** One past the highest objective index; paused objectives keep their slot so indexes stay stable. */
  objectiveSlots: number;
  /** Codes of every objective and KR, including the ones left out of the tree. */
  codes: OkrCodes;
};

export type OkrCodes = ReturnType<typeof okrCodes>;

export const OBJECTIVE_COLORS = 5;

export function objectiveColor(index: number) {
  return `var(--chart-${(index % OBJECTIVE_COLORS) + 1})`;
}

function span(items: { start: string | null; end: string | null }[]) {
  const starts = items.map((i) => i.start).filter((d): d is string => d !== null);
  const ends = items.map((i) => i.end).filter((d): d is string => d !== null);
  return {
    start: starts.length ? starts.reduce((a, b) => (a < b ? a : b)) : null,
    end: ends.length ? ends.reduce((a, b) => (a > b ? a : b)) : null,
  };
}

function byPosition<T extends { position: number; id: number }>(items: readonly T[]) {
  return [...items].sort((a, b) => a.position - b.position || a.id - b.id);
}

const isActive = (item: { active?: boolean }) => item.active !== false;

/**
 * O/KR codes are counted over every objective and KR, dropped or paused ones included, so a code
 * keeps pointing at the same item on every page after an option takes something out of the plan.
 */
export function okrCodes(objectives: readonly ObjectiveOut[]) {
  const objectiveCodes = new Map<number, { index: number; code: string }>();
  const krCodes = new Map<number, string>();
  byPosition(objectives).forEach((objective, oi) => {
    objectiveCodes.set(objective.id, { index: oi, code: `O${oi + 1}` });
    byPosition(objective.key_results).forEach((kr, ki) => krCodes.set(kr.id, `KR ${oi + 1}.${ki + 1}`));
  });
  return { objectives: objectiveCodes, krs: krCodes };
}

function taskDays(task: TaskOut, placed: ScheduledTaskOut | null): AllocationOut[] {
  if (task.pinned && task.pinned_allocations.length > 0 && task.status !== "done") {
    return [...task.pinned_allocations].sort((a, b) => a.date.localeCompare(b.date));
  }
  return placed?.allocations ?? [];
}

export function buildPlanView(detail: QuarterDetail, schedule: QuarterSchedule | null): PlanView {
  const scheduled = new Map((schedule?.tasks ?? []).map((s) => [s.task_id, s]));
  const late = new Set((schedule?.unscheduled ?? []).map((u) => u.task_id));
  const tasks = new Map<number, TaskView>();

  const numbered = <T extends { position: number; id: number; active?: boolean }>(items: readonly T[]) =>
    byPosition(items)
      .map((item, index) => ({ item, index }))
      .filter(({ item }) => isActive(item));

  const objectives = numbered(detail.objectives).map<ObjectiveView>(({ item: objective, index: oi }) => {
    const krs = numbered(objective.key_results).map<KrView>(({ item: kr, index: ki }) => {
      const krCode = `KR ${oi + 1}.${ki + 1}`;
      const taskViews = byPosition(kr.tasks).map<TaskView>((task, ti) => {
        const placed = scheduled.get(task.id) ?? null;
        const days = taskDays(task, placed);
        const done = task.status === "done";
        const isLate = late.has(task.id) && !(task.pinned && days.length > 0);
        const view: TaskView = {
          task,
          code: `T${oi + 1}.${ki + 1}.${ti + 1}`,
          objectiveIndex: oi,
          krCode,
          scheduled: placed,
          late: isLate && !done,
          days,
          start: days[0]?.date ?? null,
          end: days.at(-1)?.date ?? null,
          dependsOn: task.depends_on,
          blocks: [],
          done,
          pinned: task.pinned,
          isNew: task.plan_run_id === null,
          unplaced: days.length === 0 && !isLate && !done,
        };
        tasks.set(task.id, view);
        return view;
      });
      return {
        kr,
        code: krCode,
        tasks: taskViews,
        minutes: taskViews.reduce((sum, t) => sum + t.task.estimate_minutes, 0),
        ...span(taskViews),
      };
    });
    return {
      objective,
      index: oi,
      code: `O${oi + 1}`,
      krs,
      minutes: krs.reduce((sum, k) => sum + k.minutes, 0),
      ...span(krs),
    };
  });

  for (const view of tasks.values()) {
    for (const dep of view.dependsOn) tasks.get(dep)?.blocks.push(view.task.id);
  }

  const krCount = objectives.reduce((sum, o) => sum + o.krs.length, 0);
  const codes = okrCodes(detail.objectives);
  return {
    objectives,
    dropped: droppedItems(detail, codes),
    tasks,
    taskCount: tasks.size,
    krCount,
    totalMinutes: objectives.reduce((sum, o) => sum + o.minutes, 0),
    objectiveSlots: detail.objectives.length,
    codes,
  };
}

function droppedItems(detail: QuarterDetail, codes: OkrCodes): DroppedItem[] {
  const taskCount = (krs: readonly KeyResultOut[]) => krs.reduce((sum, kr) => sum + kr.tasks.length, 0);
  return byPosition(detail.objectives).flatMap<DroppedItem>((objective) => {
    if (!isActive(objective)) {
      return [
        {
          kind: "objective",
          objective,
          code: codes.objectives.get(objective.id)!.code,
          krCount: objective.key_results.length,
          taskCount: taskCount(objective.key_results),
        },
      ];
    }
    return byPosition(objective.key_results)
      .filter((kr) => !isActive(kr))
      .map((kr) => ({ kind: "kr", kr, objective, code: codes.krs.get(kr.id)!, taskCount: kr.tasks.length }));
  });
}

export function droppedTotals(items: readonly DroppedItem[]) {
  return items.reduce(
    (acc, item) => ({
      krs: acc.krs + (item.kind === "objective" ? item.krCount : 1),
      tasks: acc.tasks + item.taskCount,
    }),
    { krs: 0, tasks: 0 },
  );
}

export function hours(minutes: number) {
  return Math.round((minutes / 60) * 10) / 10;
}

// --- feasibility ----------------------------------------------------------------------------

export type LateKr = { kr: KrView; objectiveIndex: number; count: number; minutes: number };

export type FeasibilitySummary = {
  status: QuarterSchedule["feasibility"]["status"];
  demandMinutes: number;
  supplyMinutes: number;
  bufferedSupplyMinutes: number;
  bufferMinutes: number;
  bufferStart: string | null;
  usedPercent: number;
  shortageMinutes: number;
  bufferUsedMinutes: number;
  bufferTaskCount: number;
  lateTaskCount: number;
  lateMinutes: number;
  finishDate: string | null;
  windowEnd: string;
  lateKrs: LateKr[];
  /** Tasks, pins or the calendar changed after this schedule was made. */
  stale: boolean;
};

export function summarizeFeasibility(schedule: QuarterSchedule, view: PlanView): FeasibilitySummary {
  const f = schedule.feasibility;
  const bufferMinutes = f.supply_minutes - f.buffered_supply_minutes;
  const lateByKr = new Map<number, { count: number; minutes: number }>();
  let lateMinutes = 0;
  for (const u of schedule.unscheduled) {
    const minutes = view.tasks.get(u.task_id)?.task.estimate_minutes ?? 0;
    lateMinutes += minutes;
    const entry = lateByKr.get(u.key_result_id) ?? { count: 0, minutes: 0 };
    lateByKr.set(u.key_result_id, { count: entry.count + 1, minutes: entry.minutes + minutes });
  }
  const lateKrs: LateKr[] = [];
  for (const o of view.objectives) {
    for (const kr of o.krs) {
      const entry = lateByKr.get(kr.kr.id);
      if (entry) lateKrs.push({ kr, objectiveIndex: o.index, ...entry });
    }
  }
  const ends = schedule.tasks.map((t) => t.end_date);
  return {
    status: f.status,
    demandMinutes: f.demand_minutes,
    supplyMinutes: f.supply_minutes,
    bufferedSupplyMinutes: f.buffered_supply_minutes,
    bufferMinutes,
    bufferStart: f.buffer_start,
    usedPercent: f.supply_minutes > 0 ? Math.round((f.demand_minutes / f.supply_minutes) * 100) : 0,
    shortageMinutes: Math.max(0, f.demand_minutes - f.supply_minutes),
    bufferUsedMinutes: Math.min(bufferMinutes, Math.max(0, f.demand_minutes - f.buffered_supply_minutes)),
    bufferTaskCount: schedule.tasks.filter((t) => t.uses_buffer).length,
    lateTaskCount: schedule.unscheduled.length,
    lateMinutes,
    finishDate: ends.length ? ends.reduce((a, b) => (a > b ? a : b)) : null,
    windowEnd: schedule.window_end,
    lateKrs,
    stale: schedule.stale,
  };
}

// --- calendar -------------------------------------------------------------------------------

export type CalendarBlock = {
  id: string;
  date: string;
  minutes: number;
  view: TaskView;
  part: number;
  parts: number;
};

export function calendarBlocks(view: PlanView): CalendarBlock[] {
  const blocks = [...view.tasks.values()].flatMap((task) =>
    task.days.map((a: AllocationOut, i) => ({
      id: `${task.task.id}-${a.date}`,
      date: a.date,
      minutes: a.minutes,
      view: task,
      part: i + 1,
      parts: task.days.length,
    })),
  );
  return blocks.sort(
    (a, b) =>
      a.date.localeCompare(b.date) ||
      (a.view.start ?? "").localeCompare(b.view.start ?? "") ||
      a.view.code.localeCompare(b.view.code, undefined, { numeric: true }),
  );
}

/** Minutes of unfinished work per day, matching what the day cells list. */
export function dayLoads(blocks: readonly CalendarBlock[]) {
  const loads = new Map<string, number>();
  for (const block of blocks) {
    if (block.view.done) continue;
    loads.set(block.date, (loads.get(block.date) ?? 0) + block.minutes);
  }
  return loads;
}

/** A KR's expected completion day, drawn on the calendar as "◆ KR 1.2". */
export type KrMarker = { krId: number; date: string; krCode: string; objectiveIndex: number; text: string };

export function krMarkers(
  view: PlanView,
  milestones: readonly { key_result_id: number; expected_completion_date: string | null }[],
): KrMarker[] {
  const dates = new Map(milestones.map((m) => [m.key_result_id, m.expected_completion_date]));
  return view.objectives.flatMap((o) =>
    o.krs.flatMap((kr) => {
      const date = dates.get(kr.kr.id);
      return date ? [{ krId: kr.kr.id, date, krCode: kr.code, objectiveIndex: o.index, text: kr.kr.text }] : [];
    }),
  );
}

export function blocksByDate(blocks: readonly CalendarBlock[]) {
  const map = new Map<string, CalendarBlock[]>();
  for (const block of blocks) {
    const list = map.get(block.date) ?? [];
    list.push(block);
    map.set(block.date, list);
  }
  return map;
}

export function daysByDate(days: readonly ScheduleDay[]) {
  return new Map(days.map((d) => [d.date, d]));
}

export function taskMatches(view: TaskView, query: string) {
  const q = query.trim().toLocaleLowerCase();
  if (!q) return true;
  return (
    view.task.title.toLocaleLowerCase().includes(q) ||
    view.task.description.toLocaleLowerCase().includes(q) ||
    view.code.toLocaleLowerCase().includes(q)
  );
}
